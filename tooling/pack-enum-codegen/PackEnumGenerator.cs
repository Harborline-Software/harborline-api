using System.Globalization;
using System.Text;
using System.Text.Json;

namespace Harborline.Api.Tooling.PackEnumCodegen;

public static class PackEnumGenerator
{
    public static IReadOnlyDictionary<string, byte[]> Generate(byte[] export,
        IReadOnlyDictionary<string, string> documentation)
    {
        using var document = JsonDocument.Parse(export);
        var registry = document.RootElement;
        if (registry.GetProperty("schemaVersion").GetInt32() != 1)
            throw new InvalidDataException("Unsupported content-kinds export schemaVersion.");

        var kinds = registry.GetProperty("kinds").EnumerateArray().ToArray();
        foreach (var kind in kinds)
            if (kind.GetProperty("status").GetString() is not ("shipped" or "reserved"))
                throw new InvalidDataException("Unknown content-kind status.");

        return new Dictionary<string, byte[]>
        {
            ["packages/foundation-packs/Model/PackContentKind.g.cs"] = Render("PackContentKind", "Model",
                kinds.Where(row => row.GetProperty("status").GetString() == "shipped"),
                "// Reserved content kinds (never enum members): " + string.Join(", ", Ordered(kinds
                    .Where(row => row.GetProperty("status").GetString() == "reserved"))
                    .Select(row => $"{Name(row)} = {Value(row)}"))),
            ["packages/foundation-packs/Graph/PackPillar.g.cs"] = Render("PackPillar", "Graph",
                registry.GetProperty("pillars").EnumerateArray()),
        };

        byte[] Render(string type, string area, IEnumerable<JsonElement> rows, string? reserved = null)
        {
            var lines = new List<string>
            {
                "// <auto-generated />",
                "// Run: dotnet run --project tooling/pack-enum-codegen",
                "// Source: content-kinds export in the pinned Harborline.Foundation.Definitions package.",
            };
            if (reserved is not null) lines.Add(reserved);
            if (area == "Graph") lines.Add("using Harborline.Api.Foundation.Packs.Model;");
            lines.AddRange(["", $"namespace Harborline.Api.Foundation.Packs.{area};", "", Doc(type),
                $"public enum {type}", "{"]);
            foreach (var row in Ordered(rows))
            {
                lines.AddRange(Doc($"{type}.{Name(row)}").Split('\n').Select(line => "    " + line));
                lines.Add($"    {Name(row)} = {Value(row)},");
                lines.Add("");
            }
            if (type == "PackContentKind")
                lines.AddRange(Doc(type + ".$footer").Split('\n').Select(line => "    " + line));
            else
                lines.RemoveAt(lines.Count - 1);
            lines.Add("}");
            return Encoding.UTF8.GetBytes(string.Join('\n', lines) + "\n");
        }

        string Doc(string key) => documentation.TryGetValue(key, out var text) && !string.IsNullOrWhiteSpace(text)
            ? text : throw new InvalidDataException($"Missing documentation: {key}");
    }

    private static IEnumerable<JsonElement> Ordered(IEnumerable<JsonElement> rows) => rows
        .OrderBy(row => row.GetProperty("value").GetInt32()).ThenBy(Name, StringComparer.Ordinal);

    private static string Name(JsonElement row) => row.GetProperty("name").GetString()
        ?? throw new InvalidDataException("Missing registry member name.");

    private static string Value(JsonElement row) => row.GetProperty("value").GetInt32()
        .ToString(CultureInfo.InvariantCulture);

    public static int Run(IReadOnlyDictionary<string, byte[]> outputs, string root, bool check,
        TextWriter diagnostics)
    {
        var stale = false;
        foreach (var (relative, bytes) in outputs)
        {
            var path = Path.Combine(root, relative);
            if (check)
            {
                if (!File.Exists(path) || !File.ReadAllBytes(path).AsSpan().SequenceEqual(bytes))
                {
                    diagnostics.WriteLine($"Generated pack enum is stale: {relative}");
                    stale = true;
                }
            }
            else
            {
                Directory.CreateDirectory(Path.GetDirectoryName(path)!);
                File.WriteAllBytes(path, bytes);
            }
        }
        return stale ? 1 : 0;
    }
}
