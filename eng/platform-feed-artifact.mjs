#!/usr/bin/env node
// Same-run dependency artifact only. Never reuse API outputs or verification evidence.
import {execFileSync} from 'node:child_process'
import {createHash} from 'node:crypto'
import {lstatSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, writeFileSync} from 'node:fs'
import path from 'node:path'
import {inflateRawSync} from 'node:zlib'
import {readPin, assertProducers} from './build-local-feed.mjs'

const root = path.resolve(import.meta.dirname, '..')
export const sha256 = bytes => createHash('sha256').update(bytes).digest('hex')
const canonical = value => JSON.stringify(value, (_, item) => item && typeof item === 'object' && !Array.isArray(item)
  ? Object.fromEntries(Object.entries(item).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)) : item)
const props = version => [
  '<!-- Generated by eng/build-local-feed.mjs; .feed is gitignored. -->', '<Project>', '  <PropertyGroup>',
  `    <HarborlinePackedVersion>${version}</HarborlinePackedVersion>`, '  </PropertyGroup>', '</Project>', '',
].join('\n')

export function feedIdentity({pin, platformTree, plan, sdk, node, os, arch, imageOS, imageVersion, scripts, globalJson}) {
  if (os !== 'linux' || !imageOS || !imageVersion) throw new Error('feed reuse requires an identified Linux runner image')
  return {schemaVersion: 1, platform: {repository: pin.repository, commit: pin.commit, tree: platformTree},
    producers: pin.producers, packageGraph: {tree: platformTree, projects: plan.commands.map(args => path.basename(args[1])),
      packedVersion: plan.packedVersion},
    pack: {configuration: 'Release', directoryBuildTargets: 'platform/Directory.Build.targets', nodeReuse: false, maxCpuCount: 6},
    sdk, node, os, arch, imageOS, imageVersion, scripts, globalJson}
}

function currentIdentity(platform, pin) {
  // The existing builder independently checks commit, clean checkout, producer inventory and version.
  const plan = JSON.parse(execFileSync(process.execPath, ['eng/build-local-feed.mjs', '--dry-run'], {
    cwd: root, encoding: 'utf8', env: {...process.env, HARBORLINE_PLATFORM_REPO: platform},
  }))
  const platformTree = execFileSync('git', ['-C', platform, 'rev-parse', `${pin.commit}^{tree}`], {encoding: 'utf8'}).trim()
  const scripts = Object.fromEntries(['eng/build-local-feed.mjs', 'eng/platform-feed-artifact.mjs',
    '.github/actions/platform-feed/action.yml'].map(file => [file, sha256(readFileSync(path.join(root, file)))]))
  return feedIdentity({pin, platformTree, plan,
    sdk: execFileSync('dotnet', ['--version'], {cwd: root, encoding: 'utf8'}).trim(), node: process.version,
    os: process.platform, arch: process.arch, imageOS: process.env.ImageOS, imageVersion: process.env.ImageVersion,
    scripts, globalJson: sha256(readFileSync(path.join(root, 'global.json')))})
}

// Fail closed on archive forms the existing dotnet pack path does not emit.
export function packageMetadata(raw) {
  let offset = 0, nuspec = null
  const names = new Set(), assemblies = []
  while (offset + 30 <= raw.length && raw.readUInt32LE(offset) === 0x04034b50) {
    const flags = raw.readUInt16LE(offset + 6), method = raw.readUInt16LE(offset + 8)
    const compressed = raw.readUInt32LE(offset + 18), length = raw.readUInt32LE(offset + 22)
    const nameLength = raw.readUInt16LE(offset + 26), extraLength = raw.readUInt16LE(offset + 28)
    const start = offset + 30 + nameLength + extraLength, end = start + compressed
    if (end > raw.length || flags & 9 || ![0, 8].includes(method)) throw new Error('unsupported or truncated package archive')
    const name = raw.toString('utf8', offset + 30, offset + 30 + nameLength)
    if (!name || name.includes('\\') || name.startsWith('/') || name.split('/').includes('..') || names.has(name.toLowerCase())) {
      throw new Error('unsafe or duplicate package entry')
    }
    names.add(name.toLowerCase())
    if (/^lib\/[^/]+\/[^/]+\.dll$/.test(name)) assemblies.push(path.posix.basename(name))
    if (/^[^/]+\.nuspec$/.test(name)) {
      if (nuspec !== null) throw new Error('duplicate nuspec')
      const body = raw.subarray(start, end)
      const unpacked = method === 8 ? inflateRawSync(body, {maxOutputLength: 1024 * 1024}) : body
      if (unpacked.length !== length) throw new Error('invalid nuspec length')
      nuspec = unpacked.toString('utf8')
    }
    offset = end
  }
  if (nuspec === null || !assemblies.length) throw new Error('package missing nuspec or lib assembly')
  const one = tag => {
    const matches = [...nuspec.matchAll(new RegExp(`<${tag}>([^<]+)</${tag}>`, 'g'))]
    if (matches.length !== 1) throw new Error(`package requires exactly one ${tag}`)
    return matches[0][1]
  }
  const dependencies = [...nuspec.matchAll(/<dependency\b([^>]+)\/?\s*>/g)].map(([, attributes]) => {
    const id = /\bid="([^"]+)"/.exec(attributes)?.[1]
    const version = /\bversion="([^"]+)"/.exec(attributes)?.[1]
    if (!id || !version) throw new Error('dependency must name id and version')
    return {id, version}
  })
  return {id: one('id'), version: one('version'), assemblies, dependencies, assembly: assemblies[0]}
}

export function verifyFeed(files, pin, version) {
  if (!/^[0-9A-Za-z.-]+$/.test(version)) throw new Error('invalid packed version')
  const expected = [...Object.keys(pin.producers).map(id => `${id}.${version}.nupkg`), 'packed-version.props'].sort()
  if (JSON.stringify(files.map(file => file.name).sort()) !== JSON.stringify(expected)) throw new Error('feed file inventory mismatch')
  const packages = files.filter(file => file.name.endsWith('.nupkg')).map(file => {
    const metadata = packageMetadata(file.bytes)
    if (file.name !== `${metadata.id}.${version}.nupkg` || metadata.version !== version) throw new Error('package version or filename mismatch')
    if (metadata.assemblies.some(assembly => assembly !== pin.producers[metadata.id])) throw new Error('package assembly mismatch')
    return metadata
  })
  assertProducers(packages, pin)
  const ids = new Set(packages.map(({id}) => id.toLowerCase()))
  for (const {id, dependencies} of packages) for (const dependency of dependencies) {
    if (!/^Harborline\./i.test(dependency.id)) continue
    if (!ids.has(dependency.id.toLowerCase())) throw new Error(`missing first-party dependency: ${id} -> ${dependency.id}`)
    // Every producer uses this one content-derived prerelease. Refuse unfamiliar range forms.
    if (![version, `[${version}]`, `[${version},)`].includes(dependency.version)) {
      throw new Error(`first-party dependency version mismatch: ${id} -> ${dependency.id} ${dependency.version}`)
    }
  }
  if (!files.find(file => file.name === 'packed-version.props').bytes.equals(Buffer.from(props(version)))) throw new Error('packed-version.props mismatch')
  return packages.map(({id, version, assemblies, dependencies}) => ({id, version, assemblies, dependencies}))
    .sort((a, b) => a.id < b.id ? -1 : 1)
}

export function createBundle(files, identity, pin) {
  const closure = verifyFeed(files, pin, identity.packageGraph.packedVersion)
  return Buffer.from(canonical({schemaVersion: 1, identity, closure,
    files: [...files].sort((a, b) => a.name < b.name ? -1 : 1).map(({name, bytes}) =>
      ({name, size: bytes.length, sha256: sha256(bytes), base64: bytes.toString('base64')}))}))
}

export function validateBundle(raw, digest, identity, pin) {
  if (!/^[a-f0-9]{64}$/.test(digest) || sha256(raw) !== digest) throw new Error('feed artifact digest mismatch')
  const bundle = JSON.parse(raw)
  if (bundle.schemaVersion !== 1 || !bundle.identity) throw new Error('feed artifact identity mismatch')
  const environment = ['sdk', 'node', 'os', 'arch', 'imageOS', 'imageVersion']
  const sourceIdentity = value => Object.fromEntries(Object.entries(value).filter(([key]) => !environment.includes(key)))
  if (canonical(sourceIdentity(bundle.identity)) !== canonical(sourceIdentity(identity))) throw new Error('feed artifact identity mismatch')
  const misses = environment.filter(key => bundle.identity[key] !== identity[key])
  if (!Array.isArray(bundle.files) || bundle.files.length !== Object.keys(pin.producers).length + 1) throw new Error('feed file inventory mismatch')
  const files = bundle.files.map(file => {
    if (typeof file.name !== 'string' || !/^[A-Za-z0-9.-]+$/.test(file.name) || typeof file.base64 !== 'string') throw new Error('unsafe feed filename or content')
    const bytes = Buffer.from(file.base64, 'base64')
    if (bytes.toString('base64') !== file.base64 || bytes.length !== file.size || sha256(bytes) !== file.sha256) throw new Error(`feed file digest mismatch: ${file.name}`)
    return {name: file.name, bytes}
  })
  if (canonical(verifyFeed(files, pin, identity.packageGraph.packedVersion)) !== canonical(bundle.closure)) throw new Error('feed dependency closure mismatch')
  // Validate all transferred bytes before classifying a known environment mismatch as a miss.
  // No artifact is materialized on this path. Source/graph/script mismatches above remain fatal.
  if (misses.length) {
    const error = new Error(`feed artifact identity mismatch (environment key miss): ${misses.join(', ')}`)
    error.code = 'FEED_ENVIRONMENT_MISS'
    throw error
  }
  return files
}

export function materializeFeed(files, feed) {
  const staging = `${feed}.verified-${process.pid}`
  if (path.basename(feed) !== '.feed') throw new Error('destination must be the consumer .feed')
  if (files.some(file => !/^[A-Za-z0-9.-]+$/.test(file.name)) || new Set(files.map(file => file.name.toLowerCase())).size !== files.length) {
    throw new Error('unsafe or duplicate feed filename')
  }
  mkdirSync(staging) // Refuse an existing staging directory rather than trusting its contents.
  try {
    for (const {name, bytes} of files) writeFileSync(path.join(staging, name), bytes, {flag: 'wx'})
    rmSync(feed, {recursive: true, force: true})
    renameSync(staging, feed)
  } finally { rmSync(staging, {recursive: true, force: true}) }
}

if (import.meta.main) {
  const [command, platform, transfer, digest] = process.argv.slice(2)
  if (!['create', 'restore'].includes(command) || !platform || !transfer || (command === 'restore' && !digest)) {
    throw new Error('usage: platform-feed-artifact.mjs <create|restore> <platform> <bundle> [expected-digest]')
  }
  const pin = readPin(), identity = currentIdentity(path.resolve(platform), pin), feed = path.join(root, '.feed')
  if (command === 'create') {
    const files = readdirSync(feed).map(name => {
      if (!lstatSync(path.join(feed, name)).isFile()) throw new Error('feed must contain only regular files')
      return {name, bytes: readFileSync(path.join(feed, name))}
    })
    const raw = createBundle(files, identity, pin)
    writeFileSync(transfer, raw, {flag: 'wx'})
    console.log(`digest=${sha256(raw)}`)
    console.log(`identity=${sha256(canonical(identity))}`)
  } else {
    if (!lstatSync(transfer).isFile()) throw new Error('feed bundle must be a regular file')
    try {
      const files = validateBundle(readFileSync(transfer), digest, identity, pin)
      materializeFeed(files, feed)
      console.log(`platform-feed: restored complete same-run dependency feed (${files.length - 1} packages); API proof remains fresh`)
    } catch (error) {
      if (error.code !== 'FEED_ENVIRONMENT_MISS') throw error
      console.error(`platform-feed: ${error.message}; artifact refused, fresh pack required`)
      process.exitCode = 3
    }
  }
}
